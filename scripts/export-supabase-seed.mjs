import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { openDatabase } from '../src/database.mjs';

const output = resolve(process.argv[2] || 'supabase/seed.sql');
const db = openDatabase();

const sqlText = value => value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const jsonb = value => value == null ? 'null' : `${sqlText(value)}::jsonb`;

const content = db.prepare(`
  select collection, id, draft, published, updated_at
  from content
  order by collection, id
`).all();

const media = db.prepare(`
  select id, path, name, alt, created_at
  from media
  order by id
`).all();

const lines = [
  '-- Generated by: npm run supabase:seed',
  '-- Contains public website content and media metadata only.',
  '-- It intentionally excludes users, password hashes, sessions, requests and audit records.',
  'begin;',
  '',
];

for (const row of content) {
  lines.push(
    `insert into public.content (collection, id, draft, published, updated_at) values (${sqlText(row.collection)}, ${sqlText(row.id)}, ${jsonb(row.draft)}, ${jsonb(row.published)}, ${sqlText(row.updated_at)}::timestamptz)`,
    'on conflict (collection, id) do update set',
    '  draft = excluded.draft,',
    '  published = excluded.published,',
    '  updated_at = excluded.updated_at;',
    '',
  );
}

for (const row of media) {
  const extension = row.path.split('.').pop()?.toLowerCase();
  const mime = ({ png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', webp: 'image/webp', mp4: 'video/mp4' })[extension] || null;
  lines.push(
    `insert into public.media (id, path, storage_path, name, alt, mime_type, created_at) values (${sqlText(row.id)}, ${sqlText(row.path)}, null, ${sqlText(row.name)}, ${sqlText(row.alt)}, ${sqlText(mime)}, ${sqlText(row.created_at)}::timestamptz)`,
    'on conflict (id) do update set',
    '  path = excluded.path,',
    '  name = excluded.name,',
    '  alt = excluded.alt,',
    '  mime_type = excluded.mime_type;',
    '',
  );
}

lines.push('commit;', '');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, lines.join('\n'), 'utf8');
console.log(`Exported ${content.length} content rows and ${media.length} media rows to ${output}`);
