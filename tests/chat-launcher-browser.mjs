import assert from 'node:assert/strict';
import {createRequire} from 'node:module';

const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/kovac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const origin=process.env.QA_ORIGIN||'http://127.0.0.1:3001';
const browser=await chromium.launch({channel:'chrome',headless:true});

try{
  const page=await browser.newPage({viewport:{width:1366,height:900}});
  await page.route('**/api/chat/session',route=>route.fulfill({json:{token:'browser-test-session',expires:Date.now()+3_600_000,aiAvailable:true}}));
  await page.goto(origin+'/?lang=en');
  const launcher=page.locator('.chat-launch');
  await launcher.waitFor();
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(34, 35, 68)');
  assert.match(await page.locator('.chat-launch-icon img').getAttribute('src'),/chat-animated\.svg/);
  assert.equal(await page.locator('.chat-active-icon').evaluate(el=>getComputedStyle(el).display),'none');

  await launcher.click();
  await page.locator('.conversation-consent-icon').click();
  await page.locator('.conversation-start button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#cp-chat')?.classList.contains('has-session'));
  assert.match(await launcher.evaluate(el=>getComputedStyle(el).backgroundImage),/linear-gradient/);
  assert.equal(await page.locator('.chat-active-icon').evaluate(el=>getComputedStyle(el).display),'block');
  assert.equal(await launcher.getAttribute('aria-label'),'Minimise chat');
  assert.equal(await page.locator('.chat-launch span').evaluate(el=>getComputedStyle(el).display),'none');
  assert.equal(await page.locator('.chat-active-icon').evaluate(el=>getComputedStyle(el).animationName),'none');
  assert.deepEqual(await page.locator('.chat-writing-line').evaluateAll(els=>els.map(el=>getComputedStyle(el).animationName)),['chat-line-write','chat-line-write','chat-line-write']);
  assert.deepEqual(await page.locator('.chat-writing-line').evaluateAll(els=>els.map(el=>el.getBBox().x)),[6,6,6]);
  await page.locator('#conversation-input').fill('Hello');
  assert.deepEqual(await page.locator('.chat-writing-line').evaluateAll(els=>els.map(el=>getComputedStyle(el).animationName)),['none','none','none']);
  await page.locator('#conversation-input').fill('');
  assert.deepEqual(await page.locator('.chat-writing-line').evaluateAll(els=>els.map(el=>getComputedStyle(el).animationName)),['chat-line-write','chat-line-write','chat-line-write']);

  await page.goto(origin+'/preise?lang=en');
  await page.waitForFunction(()=>document.querySelector('#cp-chat')?.classList.contains('resumed-session'));
  assert.equal(await page.locator('.chat-launch span').textContent(),'Continue chat');
  await page.waitForFunction(()=>document.querySelector('.chat-launch')?.getBoundingClientRect().width>170);
  await launcher.click();
  assert.equal(await page.locator('#cp-chat').evaluate(el=>el.classList.contains('resumed-session')),false);
  assert.match(await launcher.evaluate(el=>getComputedStyle(el).backgroundImage),/linear-gradient/);
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).color),'rgb(255, 255, 255)');
  assert.ok(await page.locator('.conversation-thread').textContent());

  assert.equal(await page.locator('.chat-minimise').getAttribute('aria-label'),'Minimise chat');
  assert.equal(await page.locator('.chat-close').getAttribute('aria-label'),'End chat');
  await page.locator('.chat-minimise').click();
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(220, 238, 245)');
  assert.equal(await launcher.evaluate(el=>el===document.activeElement),false);
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  assert.equal(await page.locator('.chat-active-icon').evaluate(el=>getComputedStyle(el).display),'block');
  assert.equal(await page.locator('.chat-launch span').textContent(),'Continue chat');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#cp-chat')?.classList.contains('resumed-session'));
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(220, 238, 245)');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('.chat-launch span').evaluate(el=>getComputedStyle(el).display),'block');
  assert.ok(await launcher.evaluate(el=>{const bounds=el.getBoundingClientRect();return bounds.left>=0&&bounds.right<=innerWidth;}));
  assert.ok(await page.locator('.chat-active-icon').evaluate(el=>{const icon=el.getBoundingClientRect(),phone=document.querySelector('.mobile-call').getBoundingClientRect();return Math.abs(icon.left+icon.width/2-(phone.left-39))<2;}));
  await page.setViewportSize({width:320,height:700});
  await page.waitForFunction(()=>document.querySelector('.chat-launch')?.getBoundingClientRect().width<=153);
  assert.ok(await launcher.evaluate(el=>el.getBoundingClientRect().left>=0));
  assert.ok(await page.locator('.chat-launch span').evaluate(el=>el.scrollWidth<=el.clientWidth));
  await page.setViewportSize({width:390,height:844});
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).display),'flex');
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).borderTopLeftRadius),'40px');
  const minimisedIconCenter=await page.locator('.chat-active-icon').evaluate(el=>{const bounds=el.getBoundingClientRect();return bounds.left+bounds.width/2;});
  await launcher.click();
  assert.match(await launcher.evaluate(el=>getComputedStyle(el).backgroundImage),/linear-gradient/);
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).display),'flex');
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).borderTopLeftRadius),'40px');
  assert.equal(await page.locator('.chat-launch span').evaluate(el=>getComputedStyle(el).display),'block');
  assert.match(await launcher.evaluate(el=>getComputedStyle(el).transitionProperty),/width/);
  await page.waitForFunction(()=>Math.abs(document.querySelector('.chat-launch')?.getBoundingClientRect().width-58)<1);
  assert.ok(Math.abs(await page.locator('.chat-active-icon').evaluate(el=>{const bounds=el.getBoundingClientRect();return bounds.left+bounds.width/2;})-minimisedIconCenter)<1);
  assert.ok(await page.locator('.chat-active-icon').evaluate(el=>{const icon=el.getBoundingClientRect(),button=el.closest('button').getBoundingClientRect();return Math.abs(icon.left+icon.width/2-button.left-button.width/2)<1;}));
  await page.locator('.chat-minimise').click();
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await launcher.click();
  await page.setViewportSize({width:390,height:500});
  await page.locator('#conversation-input').click();
  await page.waitForFunction(()=>document.querySelector('#cp-chat')?.classList.contains('keyboard-visible'));
  assert.ok(await page.locator('.chat-window').evaluate(el=>{const bounds=el.getBoundingClientRect();return bounds.top>=35&&bounds.top<=55&&bounds.bottom<=innerHeight-10;}));
  await page.setViewportSize({width:390,height:844});
  await page.locator('.chat-close').click();
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(34, 35, 68)');
  assert.equal(await page.locator('.chat-launch-icon').evaluate(el=>getComputedStyle(el).display),'block');
  assert.equal(await page.locator('.chat-launch span').textContent(),'Chat with us');
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('citypraxis-conversation-v2')),null);
  await page.reload();
  assert.equal(await launcher.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(34, 35, 68)');
  assert.equal(await page.locator('.chat-active-icon').evaluate(el=>getComputedStyle(el).display),'none');
  console.log('Active, minimised and ended chat states verified across navigation and reload.');
}finally{
  await browser.close();
}
