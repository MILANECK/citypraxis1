import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/kovac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const origin=process.env.QA_ORIGIN||'http://127.0.0.1:3013';
const browser=await chromium.launch({channel:'chrome',headless:true});
await mkdir('test-results',{recursive:true});
try{
  const page=await browser.newPage({viewport:{width:1366,height:900},acceptDownloads:true});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin+'/termin?lang=de');
  await page.locator('.cookie-acknowledge').click();
  await page.locator('#booking-form [name=name]').fill('Browser Prüfer');
  await page.locator('#booking-form [name=email]').fill('browser@example.test');
  await page.locator('#booking-form [name=phone]').fill('+4369912682157');
  await page.locator('#booking-form [name=consent]').check();
  await page.locator('#booking-form button[type=submit]').click();
  await page.locator('.request-confirmation').waitFor();
  await page.goto(origin+'/admin');
  await page.locator('#login-form [name=email]').fill('preview@example.test');
  await page.locator('#login-form [name=password]').fill('local-preview-only-2026');
  await page.locator('#login-form button').first().click();
  await page.locator('[data-view=requests]').click();
  const request=page.locator('.request-disclosure').first();
  await request.waitFor();
  assert.equal(await request.evaluate(el=>el.open),false);
  assert.match(await request.locator('summary').textContent(),/#1.*Browser Prüfer.*Formular/s);
  await page.locator('#request-list').screenshot({path:'test-results/admin-requests-compact.png'});
  await request.locator('summary').click();
  await page.waitForTimeout(470);
  assert.equal(await request.evaluate(el=>el.open),true);
  assert.equal(await request.locator('[data-request]').count(),1);
  await page.locator('#request-list').screenshot({path:'test-results/admin-requests-open.png'});
  await request.locator('summary').click();
  await page.waitForTimeout(470);
  assert.equal(await request.evaluate(el=>el.open),false);
  await page.locator('[data-view=media]').click();
  await page.locator('.media-card').first().waitFor();
  const before=await page.locator('.media-card').count();
  await page.locator('#upload-form input[type=file]').setInputFiles('public/assets/wordmark-white.png');
  await page.locator('#upload-form [name=alt]').fill('Browser test image');
  await page.locator('#upload-form button').click();
  await page.waitForFunction(count=>document.querySelectorAll('.media-card').length===count+1,before);
  assert.equal(await page.locator('.media-card').count(),before+1);
  assert.ok(await page.locator('.media-thumb').first().evaluate(el=>el.getBoundingClientRect().height<=120));
  await page.locator('.media-grid').screenshot({path:'test-results/admin-media-compact.png'});
  const downloadEvent=page.waitForEvent('download');
  await page.locator('.media-card').first().locator('.media-card-actions a').click();
  const download=await downloadEvent;
  assert.match(download.suggestedFilename(),/citypraxis-.*\.png/);
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('.media-card').first().locator('[data-delete-media]').click();
  await page.waitForFunction(count=>document.querySelectorAll('.media-card').length===count,before);
  await page.locator('[data-view=team]').click();
  await page.locator('[data-edit]').first().click();
  assert.equal(await page.locator('#editor-dialog [name=placeholder]').count(),0);
  assert.equal(await page.locator('#editor-dialog [name=fictional]').count(),0);
  await page.locator('#editor-dialog .close-dialog').click();
  await page.goto(origin+'/ueber-uns?lang=de');
  const team=page.locator('.team-directory .team-person').first();
  await team.scrollIntoViewIfNeeded();
  await team.waitFor({state:'visible'});
  await page.waitForTimeout(850);
  assert.equal(await team.evaluate(el=>el.classList.contains('is-visible')),true);
  await team.hover();
  assert.notEqual(await team.locator('.team-photo').evaluate(el=>getComputedStyle(el).transform),'none');
  await page.locator('.team-directory .team-profiles').screenshot({path:'test-results/team-scroll-hover.png'});
  await page.goto(origin+'/?lang=de');
  const footer=await page.locator('.footer-top').textContent();
  assert.match(footer,/Öffnungszeiten/);
  assert.doesNotMatch(footer,/Samstag/);
  await page.setViewportSize({width:390,height:844});
  await page.goto(origin+'/admin');
  await page.locator('[data-view=requests]').click();
  const mobileRequest=page.locator('.request-disclosure').first();
  await mobileRequest.waitFor();
  assert.equal(await page.locator('#workspace').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await page.locator('#request-list').screenshot({path:'test-results/admin-requests-mobile.png'});
  await mobileRequest.locator('summary').click();
  await page.waitForTimeout(470);
  assert.equal(await mobileRequest.evaluate(el=>el.open),true);
  assert.deepEqual(errors,[]);
  console.log('admin requests, media, team, and footer passed');
}finally{await browser.close();}
