let activeGradient;

export async function initBookingGradient(){
  const canvas=document.getElementById('booking-gradient');
  if(!canvas||activeGradient)return;
  const stage=canvas.closest('.booking-gradient-stage');
  const form=document.getElementById('booking-form');
  const syncCanvasStart=()=>{
    if(!stage||!form)return;
    stage.style.setProperty('--booking-gradient-top',innerWidth<=767?`${Math.max(0,form.offsetTop-72)}px`:'0px');
  };
  syncCanvasStart();
  addEventListener('resize',syncCanvasStart);
  const reduceMotion=matchMedia('(prefers-reduced-motion: reduce)').matches;
  try{
    const {NeatGradient}=await import('/vendor/neat.js?v=1');
    activeGradient=new NeatGradient({
      ref:canvas,
      colors:[
        {color:'#0b3954',enabled:true},
        {color:'#3EA1C7',enabled:true},
        {color:'#bfd7ea',enabled:true},
        {color:'#691169',enabled:true},
        {color:'#741B75',enabled:true},
        {color:'#F9F3E8',enabled:false}
      ],
      speed:reduceMotion?0:1.5,
      horizontalPressure:4,
      verticalPressure:3,
      waveFrequencyX:0,
      waveFrequencyY:0,
      waveAmplitude:0,
      secondaryWaveEnabled:false,
      secondaryWaveFrequencyX:3,
      secondaryWaveFrequencyY:3,
      secondaryWaveAmplitude:5,
      secondaryWaveSpeed:0.6,
      secondaryWaveAngle:1,
      shadows:2,
      highlights:7,
      colorBrightness:1,
      colorSaturation:8,
      wireframe:false,
      antialias:false,
      colorBlending:5,
      backgroundColor:'#FF0000',
      backgroundAlpha:1,
      grainScale:3,
      grainSparsity:0,
      grainIntensity:0.15,
      grainSpeed:0,
      resolution:0.25,
      yOffset:0,
      yOffsetWaveMultiplier:1.2,
      yOffsetColorMultiplier:1.8,
      yOffsetFlowMultiplier:2,
      flowDistortionA:1.2,
      flowDistortionB:1.8,
      flowScale:1.5,
      flowEase:0.25,
      flowEnabled:false,
      enableProceduralTexture:false,
      transparentTextureVoid:false,
      textureMode:'bitmap',
      bakeEdgeSoftness:1,
      textureVoidLikelihood:0.27,
      textureVoidWidthMin:60,
      textureVoidWidthMax:420,
      textureBandDensity:1.2,
      textureColorBlending:0.06,
      textureSeed:333,
      textureEase:0.75,
      proceduralBackgroundColor:'#0E0707',
      textureShapeTriangles:20,
      textureShapeCircles:15,
      textureShapeBars:15,
      textureShapeSquiggles:10,
      domainWarpEnabled:false,
      domainWarpIntensity:0,
      domainWarpScale:3,
      vignetteIntensity:0,
      vignetteRadius:0.8,
      fresnelEnabled:false,
      fresnelPower:2,
      fresnelIntensity:0.5,
      fresnelColor:'#FFFFFF',
      iridescenceEnabled:false,
      iridescenceIntensity:0.5,
      iridescenceSpeed:1,
      prismEdgeEnabled:false,
      prismEdgeIntensity:0.5,
      prismEdgeThinness:3,
      prismEdgeSpread:1,
      prismEdgeSpeed:0.5,
      prismEdgeRipple:1,
      bloomIntensity:0,
      bloomThreshold:0.7,
      chromaticAberration:0,
      shapeType:'plane',
      shapeRotationX:0,
      shapeRotationY:0,
      shapeRotationZ:0,
      shapeAutoRotateSpeedX:0,
      shapeAutoRotateSpeedY:0,
      sphereRadius:15,
      torusRadius:15,
      torusTube:5,
      cylinderRadius:10,
      cylinderHeight:40,
      planeBend:0,
      planeTwist:0,
      silhouetteFade:0.25,
      cylinderFade:0.08,
      ribbonFade:0.05,
      flatShading:true,
      cameraLock:true,
      cameraX:0,
      cameraY:0,
      cameraZ:0,
      cameraRotationX:0,
      cameraRotationY:0,
      cameraRotationZ:0,
      cameraZoom:1
    });
    canvas.classList.add('is-ready');
    let scrollFrame=0;
    const syncScroll=()=>{
      if(reduceMotion||scrollFrame)return;
      scrollFrame=requestAnimationFrame(()=>{
        scrollFrame=0;
        if(activeGradient)activeGradient.yOffset=window.scrollY;
      });
    };
    addEventListener('scroll',syncScroll,{passive:true});
    addEventListener('pagehide',()=>{
      removeEventListener('scroll',syncScroll);
      removeEventListener('resize',syncCanvasStart);
      if(scrollFrame)cancelAnimationFrame(scrollFrame);
      activeGradient?.destroy();
      activeGradient=undefined;
    },{once:true});
  }catch{
    removeEventListener('resize',syncCanvasStart);
    canvas.classList.add('is-fallback');
  }
}
